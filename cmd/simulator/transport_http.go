package main

import (
	"bytes"
	"context"
	"crypto/tls"
	"encoding/json"
	"fmt"
	"io"
	"log/slog"
	"net/http"
	"net/url"
	"strings"
	"sync"
	"time"

	"github.com/jackc/pgx/v5/pgxpool"
)

// httpTransport is the simulator's HTTPS link to the backend (SIM_TRANSPORT=
// http) where there is no MQTT broker to publish to (Cloud Run): every tick
// it pushes the readings of a gateway's equipment to its REST_SERVER gateway
// (POST /api/datahub/rest/{alias}, flat "<equipment>/<parameter>" keys, the
// tag addresses), and it polls the gateway's queued operator commands and
// fault injections (GET /api/datahub/rest/{alias}/commands).
type httpTransport struct {
	base   string
	client *http.Client
	db     *pgxpool.Pool

	mu   sync.Mutex
	keys map[string]string // gateway alias -> API key
}

func newHTTPTransport(base string, verifyTLS bool, db *pgxpool.Pool) *httpTransport {
	tr := &http.Transport{MaxIdleConnsPerHost: 8, IdleConnTimeout: 90 * time.Second}
	if !verifyTLS {
		tr.TLSClientConfig = &tls.Config{InsecureSkipVerify: true} //nolint:gosec // the local backend's self-signed certificate
	}
	return &httpTransport{base: strings.TrimRight(base, "/"), client: &http.Client{Timeout: 10 * time.Second, Transport: tr}, db: db,
		keys: map[string]string{}}
}

// key is the gateway's API key (generated by the backend for REST_SERVER).
func (t *httpTransport) key(ctx context.Context, alias string) (string, error) {
	t.mu.Lock()
	k := t.keys[alias]
	t.mu.Unlock()
	if k != "" {
		return k, nil
	}
	if err := t.db.QueryRow(ctx, `SELECT COALESCE(secrets->>'api_key', '') FROM dh.gateways WHERE alias = $1`, alias).Scan(&k); err != nil {
		return "", fmt.Errorf("gateway %s: %w", alias, err)
	}
	if k == "" {
		return "", fmt.Errorf("gateway %s has no API key (not a REST_SERVER gateway?)", alias)
	}
	t.mu.Lock()
	t.keys[alias] = k
	t.mu.Unlock()
	return k, nil
}

func (t *httpTransport) do(ctx context.Context, method, alias, suffix string, body []byte) ([]byte, error) {
	k, err := t.key(ctx, alias)
	if err != nil {
		return nil, err
	}
	var rd io.Reader
	if body != nil {
		rd = bytes.NewReader(body)
	}
	req, err := http.NewRequestWithContext(ctx, method, t.base+"/api/datahub/rest/"+url.PathEscape(alias)+suffix, rd)
	if err != nil {
		return nil, err
	}
	req.Header.Set("X-Api-Key", k)
	if body != nil {
		req.Header.Set("Content-Type", "application/json")
	}
	resp, err := t.client.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	b, _ := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
	if resp.StatusCode == http.StatusUnauthorized {
		t.mu.Lock()
		delete(t.keys, alias) // regenerated: read it again next time
		t.mu.Unlock()
	}
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s %s: %s %s", method, alias+suffix, resp.Status, strings.TrimSpace(string(b)))
	}
	return b, nil
}

// push sends the readings of one gateway.
func (t *httpTransport) push(ctx context.Context, alias string, values map[string]any) error {
	b, _ := json.Marshal(values)
	_, err := t.do(ctx, http.MethodPost, alias, "", b)
	return err
}

// commands takes the gateway's pending commands.
func (t *httpTransport) commands(ctx context.Context, alias string) ([]Command, error) {
	b, err := t.do(ctx, http.MethodGet, alias, "/commands", nil)
	if err != nil {
		return nil, err
	}
	var res struct {
		Commands []struct {
			Device  string          `json:"device"`
			Payload json.RawMessage `json:"payload"`
		} `json:"commands"`
	}
	if err := json.Unmarshal(b, &res); err != nil {
		return nil, err
	}
	out := make([]Command, 0, len(res.Commands))
	for _, c := range res.Commands {
		var cmd Command
		if err := json.Unmarshal(c.Payload, &cmd); err != nil {
			slog.Warn("invalid command", "gateway", alias, "err", err)
			continue
		}
		cmd.Gateway, cmd.Device = alias, c.Device
		out = append(out, cmd)
	}
	return out, nil
}

// pushAll pushes every gateway's readings in parallel and waits for them
// (bounded by the client timeout).
func (t *httpTransport) pushAll(ctx context.Context, byGateway map[string]map[string]any) {
	var wg sync.WaitGroup
	for alias, values := range byGateway {
		wg.Add(1)
		go func() {
			defer wg.Done()
			if err := t.push(ctx, alias, values); err != nil && ctx.Err() == nil {
				slog.Warn("push telemetry", "gateway", alias, "err", err)
			}
		}()
	}
	wg.Wait()
}

// pollCommands queues the gateways' commands for the simulation loop until
// ctx ends.
func (t *httpTransport) pollCommands(ctx context.Context, every time.Duration, cmds chan<- Command) {
	tick := time.NewTicker(every)
	defer tick.Stop()
	for {
		select {
		case <-ctx.Done():
			return
		case <-tick.C:
		}
		for _, g := range gateways {
			list, err := t.commands(ctx, g.Alias)
			if err != nil {
				if ctx.Err() == nil {
					slog.Debug("poll commands", "gateway", g.Alias, "err", err)
				}
				continue
			}
			for _, c := range list {
				select {
				case cmds <- c:
				default:
					slog.Warn("command queue full, command dropped", "equipment", c.Device, "parameter", c.Parameter)
				}
			}
		}
	}
}
