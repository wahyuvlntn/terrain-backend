const toolLOTO = "Put the tool in maintenance mode in the automation host, apply the tool lock-out / tag-out (EMO, RF, gas and chemical " +
	"isolation) and confirm zero energy before opening any panel."

// toolSafety prefixes a cleanroom tool procedure with its safety note.
func toolSafety(s string) string {
	return "**Safety:** " + toolLOTO + " Wear cleanroom garments, safety glasses and the PPE the tool requires.\n\n" + s
}

// release is the common last step: requalify and release the tool.
const release = "Run the requalification monitors; release the tool in the automation host when they pass and record the results in the work report."

